//   aliases : matched case-insensitively on word boundaries (the skill name is included automatically)
//   exact   : matched case-sensitively (for acronyms like "REST" that are also normal words in lowercase)
//   strict  : case-sensitive AND must stand alone in a list ("Python, C, Java") — for one-letter names
